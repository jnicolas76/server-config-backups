@dataclass
class Issue:
    key: str
    message: str
    severity: str = "error"        # error | warning

    def __str__(self) -> str:
        return f"[{self.severity}] {self.key}: {self.message}"


def get(config: dict, key: str, default: Any = None) -> Any:
    node: Any = config
    for part in key.split("."):
        if not isinstance(node, dict) or part not in node:
            return default
        node = node[part]
    return node


def put(config: dict, key: str, value: Any) -> None:
    parts = key.split(".")
    node = config
    for part in parts[:-1]:
        nxt = node.get(part)
        if not isinstance(nxt, dict):
            nxt = {}
            node[part] = nxt
        node = nxt
    node[parts[-1]] = value


def apply_defaults(config: dict) -> dict:
    """Return *config* with every unset schema key filled from its default."""
    import copy
    out = copy.deepcopy(config) if config else {}
    for f in SCHEMA:
        if get(out, f.key, _MISSING) is _MISSING:
            default = f.default
            if isinstance(default, (list, dict)):
                default = copy.deepcopy(default)
            put(out, f.key, default)
    return out


class _Missing:
    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return "<missing>"


_MISSING = _Missing()

_TYPE_MAP = {
    "str": str,
    "int": int,
    "float": (int, float),
    "bool": bool,
    "list": list,
    "dict": dict,
}

KNOWN_GAMES = ("nes", "sega", "dos", "mame", "gameboy", "gba", "n64", "ps1",
               "c64", "atari2600", "atari5200", "atari7800", "arcade")
KNOWN_CREATORS = ("comics", "books", "games")
KNOWN_MOUNT_TYPES = ("nfs", "cifs")


def validate(config: dict, *, for_install: bool = True) -> list[Issue]:
    """Validate a fully-defaulted configuration.

    ``for_install=False`` relaxes rules that only matter at install time (for
    example a partially-filled wizard draft), so the same function can validate
    each wizard stage as it is entered.
    """
    issues: list[Issue] = []
    cfg = apply_defaults(config)

    for f in SCHEMA:
        value = get(cfg, f.key, _MISSING)
        if value is _MISSING or value is None:
            if f.required and for_install:
                issues.append(Issue(f.key, "is required"))
            continue

        # type
        if f.type == "enum":
            if f.choices and value not in f.choices:
                issues.append(Issue(f.key, f"must be one of {list(f.choices)}, got {value!r}"))
            continue
        expected = _TYPE_MAP.get(f.type)
        if expected and not isinstance(value, expected):
            # bool is a subclass of int; guard against silent acceptance
            if not (f.type in ("int", "float") and isinstance(value, bool) is False
                    and isinstance(value, (int, float))):
                issues.append(Issue(f.key, f"must be {f.type}, got {type(value).__name__}"))
                continue
        if f.type in ("int", "float") and isinstance(value, bool):
            issues.append(Issue(f.key, f"must be {f.type}, got bool"))
            continue

        # range
        if f.minimum is not None and isinstance(value, (int, float)) and value < f.minimum:
            issues.append(Issue(f.key, f"must be >= {f.minimum}, got {value}"))
        if f.maximum is not None and isinstance(value, (int, float)) and value > f.maximum:
            issues.append(Issue(f.key, f"must be <= {f.maximum}, got {value}"))

        # pattern
        if f.pattern and isinstance(value, str) and not re.match(f.pattern, value):
            issues.append(Issue(f.key, "has an invalid format"))

        # paths
        if MEDIA_PATH in f.tags and isinstance(value, str) and value.strip():
            try:
                check_media_path(value, label=f.key)
            except PathSafetyError as exc:
                issues.append(Issue(f.key, str(exc)))
        elif PATH in f.tags and isinstance(value, str) and value.strip():
            try:
                check_system_path(value, label=f.key)
            except PathSafetyError as exc:
                issues.append(Issue(f.key, str(exc)))

    issues.extend(_cross_field_rules(cfg, for_install=for_install))
    return issues


def _cross_field_rules(cfg: dict, *, for_install: bool) -> list[Issue]:
    issues: list[Issue] = []
    g = lambda k, d=None: get(cfg, k, d)  # noqa: E731

    # --- password strength (only when a plaintext password is present) ----
    password = g("admin.password") or ""
    if password:
        issues.extend(check_password(password))
    elif for_install and not g("admin.password_hash"):
        issues.append(Issue("admin.password", "is required"))

    # --- ports must be unique and free of well-known conflicts -----------
    ports: dict[int, str] = {}

    def claim(port: Any, owner: str) -> None:
        if not isinstance(port, int) or port <= 0:
            return
        if port in ports:
            issues.append(Issue(owner, f"port {port} is already used by {ports[port]}"))
        else:
            ports[port] = owner

    if g("network.enable_http"):
        claim(g("network.http_port"), "network.http_port")
    if g("network.tls_mode") != "none":
        claim(g("network.https_port"), "network.https_port")
    if g("modules.bookvault"):
        claim(g("modules.bookvault_port"), "modules.bookvault_port")
    if g("modules.comics"):
        claim(g("modules.comics_port"), "modules.comics_port")
    if g("epg.mode") == "extended":
        claim(g("epg.collector_port"), "epg.collector_port")
    base = g("modules.game_port_base") or 8090
    for offset, game in enumerate(g("modules.games") or []):
        claim(base + offset, f"modules.games[{game}]")

    # --- TLS -------------------------------------------------------------
    tls_mode = g("network.tls_mode")
    if tls_mode == "provided":
        for key in ("network.tls_cert_path", "network.tls_key_path"):
            if not (g(key) or "").strip():
                issues.append(Issue(key, "is required when tls_mode is 'provided'"))
    if tls_mode == "none" and not g("network.enable_http"):
        issues.append(Issue("network.tls_mode",
                            "'none' requires network.enable_http to be true, otherwise "
                            "nothing would be listening"))

    # --- trusted networks must stay private ------------------------------
    for cidr in g("network.trusted_networks") or []:
        if not isinstance(cidr, str) or not is_private_cidr(cidr):
            issues.append(Issue("network.trusted_networks",
                                f"{cidr!r} is not a private/loopback range. The setup "
                                f"wizard and EPG collector are never exposed publicly."))

    # --- listen address ---------------------------------------------------
    listen = g("network.listen_address") or ""
    if listen not in ("0.0.0.0", "::"):
        if listen and not _valid_ip(listen):
            issues.append(Issue("network.listen_address", f"{listen!r} is not a valid IP address"))

    # --- module <-> media coupling ---------------------------------------
    pairs = (
        ("modules.movies", "media.movies_root", "Movies"),
        ("modules.tv", "media.tv_root", "TV"),
        ("modules.music", "media.music_root", "Music"),
        ("modules.bookvault", "media.books_root", "Book Vault"),
        ("modules.comics", "media.comics_root", "Comics"),
    )
    for module_key, path_key, label in pairs:
        if g(module_key) and not (g(path_key) or "").strip():
            issues.append(Issue(path_key, f"{label} is enabled but no library path is set"))

    if (g("modules.games") or []) and not (g("media.games_root") or "").strip():
        issues.append(Issue("media.games_root",
                            "game modules are selected but no games root is set"))
    for game in g("modules.games") or []:
        if game not in KNOWN_GAMES:
            issues.append(Issue("modules.games", f"unknown game module {game!r}"))
    for creator in g("modules.creators") or []:
        if creator not in KNOWN_CREATORS:
            issues.append(Issue("modules.creators", f"unknown creator toolchain {creator!r}"))
    if "comics" in (g("modules.creators") or []) and not (g("media.comic_library_root") or "").strip():
        issues.append(Issue("media.comic_library_root",
                            "the comic creators need an output library path"))

    # --- media roots must not overlap or nest -----------------------------
    roots: list[tuple[str, str]] = []
    for f in SCHEMA:
        if MEDIA_PATH in f.tags:
            v = (g(f.key) or "").strip()
            if v:
                roots.append((f.key, v.rstrip("/")))
    for i, (k1, p1) in enumerate(roots):
        for k2, p2 in roots[i + 1:]:
            if p1 == p2:
                if not _overlap_allowed(k1, k2):
                    issues.append(Issue(k2, f"is the same path as {k1} ({p1})",
                                        severity="warning"))
            elif p1.startswith(p2 + "/") or p2.startswith(p1 + "/"):
                issues.append(Issue(k2, f"is nested with {k1} ({p1} / {p2}). Nested "
                                        f"libraries cause double-scanning.",
                                    severity="warning"))

    # --- Live TV / DVR / EPG ---------------------------------------------
    if g("dvr.enabled"):
        if not g("livetv.enabled"):
            issues.append(Issue("dvr.enabled", "requires livetv.enabled"))
        if not (g("media.recordings_root") or "").strip():
            issues.append(Issue("media.recordings_root", "is required when the DVR is enabled"))
        tuners = g("livetv.tuner_count") or 0
        reserved = g("livetv.reserved_tuners") or 0
        if tuners and reserved >= tuners:
            issues.append(Issue("livetv.reserved_tuners",
                                f"reserves all {tuners} tuners, leaving none for recording"))
    if g("livetv.enabled") and g("livetv.discovery") == "manual":
        addr = (g("livetv.device_address") or "").strip()
        if not addr:
            issues.append(Issue("livetv.device_address", "is required for manual discovery"))
        elif not _valid_ip(addr):
            issues.append(Issue("livetv.device_address", f"{addr!r} is not a valid IP address"))

    if g("epg.mode") == "extended":
        if not g("livetv.enabled"):
            issues.append(Issue("epg.mode", "extended guide requires Live TV"))
        if not is_private_address(g("epg.collector_bind_address") or ""):
            issues.append(Issue("epg.collector_bind_address",
                                "must be a private or loopback address; the collector "
                                "is never published to the internet"))
        if not (g("epg.channel_map") or "").strip():
            issues.append(Issue("epg.channel_map",
                                "extended EPG needs a verified channels.xml. Without one "
                                "the collector has nothing to grab.",
                                severity="warning"))
        if (g("epg.request_delay_ms") or 0) < 1000:
            issues.append(Issue("epg.request_delay_ms",
                                "below 1000 ms is likely to get the collector blocked",
                                severity="warning"))

    # --- subtitles ---------------------------------------------------------
    if g("subtitles.subdl_enabled") and not (g("subtitles.subdl_api_key") or "").strip():
        issues.append(Issue("subtitles.subdl_api_key", "is required when SubDL is enabled"))
    if g("subtitles.whisper_enabled"):
        if not g("subtitles.languages"):
            issues.append(Issue("subtitles.languages", "at least one language is required"))
        if g("subtitles.whisper_model") in ("medium", "large-v3") and \
                g("subtitles.whisper_device") == "cpu":
            issues.append(Issue("subtitles.whisper_model",
                                "medium/large-v3 on CPU can take many hours per title",
                                severity="warning"))
    if g("subtitles.whisper_start_enabled") and not g("subtitles.whisper_enabled"):
        issues.append(Issue("subtitles.whisper_start_enabled",
                            "cannot start a pipeline that is not installed"))

    # --- promo/barker channel ------------------------------------------------
    if g("promo_channel.enabled"):
        if not (g("promo_channel.model_path") or "").strip():
            issues.append(Issue("promo_channel.model_path",
                                "is required when promo_channel.enabled is true "
                                "(the Kokoro ONNX weights are not downloaded "
                                "automatically - see docs/PROMO-BARKER-CHANNEL.md)"))
        if not (g("promo_channel.voices_path") or "").strip():
            issues.append(Issue("promo_channel.voices_path",
                                "is required when promo_channel.enabled is true "
                                "(the Kokoro voice pack is not downloaded "
                                "automatically - see docs/PROMO-BARKER-CHANNEL.md)"))

    # --- transcoding safety -------------------------------------------------
    if g("transcode.library_queue_autostart") and not g("transcode.library_queue_enabled"):
        issues.append(Issue("transcode.library_queue_autostart",
                            "requires transcode.library_queue_enabled"))

    # --- licences -----------------------------------------------------------
    needs_licence = bool(g("modules.games")) or g("epg.mode") == "extended" or \
        g("subtitles.whisper_enabled")
    if for_install and needs_licence and not g("deployment.accept_licenses"):
        issues.append(Issue("deployment.accept_licenses",
                            "must be true: the selected components download "
                            "third-party software with its own licences "
                            "(see docs/THIRD-PARTY-NOTICES.md)"))

    # --- mounts -------------------------------------------------------------
    for index, mount in enumerate(g("media.mounts") or []):
        label = f"media.mounts[{index}]"
        if not isinstance(mount, dict):
            issues.append(Issue(label, "must be a mapping"))
            continue
        if mount.get("type") not in KNOWN_MOUNT_TYPES:
            issues.append(Issue(label, f"type must be one of {list(KNOWN_MOUNT_TYPES)}"))
        for required in ("source", "mountpoint"):
            if not str(mount.get(required) or "").strip():
                issues.append(Issue(label, f"{required} is required"))
        mp = str(mount.get("mountpoint") or "").strip()
        if mp:
            try:
                check_media_path(mp, label=f"{label}.mountpoint")
            except PathSafetyError as exc:
                issues.append(Issue(label, str(exc)))
        opts = str(mount.get("options") or "")
        if opts and not re.match(r"^[A-Za-z0-9_,=./:@\-+]*$", opts):
            issues.append(Issue(label, "options contain characters that are not "
                                       "valid in an fstab option list"))
        creds = str(mount.get("credentials_file") or "").strip()
        if mount.get("type") == "cifs" and creds:
            try:
                check_system_path(creds, label=f"{label}.credentials_file")
            except PathSafetyError as exc:
                issues.append(Issue(label, str(exc)))

    return issues


def _overlap_allowed(k1: str, k2: str) -> bool:
    # Comics source and generated comic library legitimately share a parent but
    # not the same directory; nothing else may collide.
    return False


def _valid_ip(value: str) -> bool:
    try:
        ipaddress.ip_address(value)
        return True
    except ValueError:
        return False


# --------------------------------------------------------------------------
# Password policy
# --------------------------------------------------------------------------

MIN_PASSWORD_LENGTH = 12

COMMON_PASSWORDS = frozenset({
    "password", "password1", "password123", "12345678", "123456789", "1234567890",
    "qwertyuiop", "letmein", "welcome", "admin", "admin123", "administrator",
    "changeme", "cinevault", "cinemediavault", "iloveyou", "monkey", "dragon",
    "baseball", "football", "sunshine", "princess", "passw0rd", "trustno1",
    "admin1", "qwerty123", "1q2w3e4r5t", "abc12345",
})


def check_password(password: str) -> list[Issue]:
    """Password rules. The password itself is never included in a message."""
    issues: list[Issue] = []
    if len(password) < MIN_PASSWORD_LENGTH:
        issues.append(Issue("admin.password",
                            f"must be at least {MIN_PASSWORD_LENGTH} characters"))
    if password.lower() in COMMON_PASSWORDS:
        issues.append(Issue("admin.password", "is a commonly used password"))
    classes = sum((
        bool(re.search(r"[a-z]", password)),
        bool(re.search(r"[A-Z]", password)),
        bool(re.search(r"\d", password)),
        bool(re.search(r"[^\w\s]", password)),
    ))
    if classes < 3:
        issues.append(Issue("admin.password",
                            "must mix at least three of: lowercase, uppercase, "
                            "digits, symbols"))
    if "\x00" in password or "\n" in password or "\r" in password:
        issues.append(Issue("admin.password", "must not contain control characters"))
    if len(password) > 256:
        issues.append(Issue("admin.password", "must be 256 characters or fewer"))
    return issues


def errors(issues: Iterable[Issue]) -> list[Issue]:
    return [i for i in issues if i.severity == "error"]


def warnings(issues: Iterable[Issue]) -> list[Issue]:
    return [i for i in issues if i.severity == "warning"]
