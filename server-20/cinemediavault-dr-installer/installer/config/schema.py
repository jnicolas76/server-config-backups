from dataclasses import dataclass, field
from typing import Any, Callable, Iterable, Sequence

# --------------------------------------------------------------------------
# Field definition
# --------------------------------------------------------------------------

SECRET = "secret"
PATH = "path"
MEDIA_PATH = "media_path"


@dataclass(frozen=True)
class Field:
    """One configuration key."""

    key: str                       # dotted path, e.g. "network.https_port"
    type: str                      # str|int|float|bool|list|dict|enum
    default: Any = None
    required: bool = False
    choices: Sequence[Any] | None = None
    minimum: float | None = None
    maximum: float | None = None
    pattern: str | None = None
    tags: frozenset[str] = frozenset()
    help: str = ""
    stage: int = 0                 # wizard stage that collects it (0 = derived)

    @property
    def is_secret(self) -> bool:
        return SECRET in self.tags

    @property
    def is_path(self) -> bool:
        return PATH in self.tags or MEDIA_PATH in self.tags


def _f(key, type_, **kw) -> Field:
    tags = kw.pop("tags", ())
    return Field(key=key, type=type_, tags=frozenset(tags), **kw)


