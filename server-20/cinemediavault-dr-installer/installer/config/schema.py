"""Declarative configuration schema for CineMediaVault.

Every setting the wizard collects and every setting an unattended
``cinemediavault.yaml`` may contain is declared here exactly once. The schema
drives four things at the same time:

* validation (types, ranges, enums, cross-field rules),
* the generated documentation in ``docs/CONFIGURATION-REFERENCE.md``,
* the redacted example configuration, and
* which values are treated as secrets and therefore never logged.

Keeping one source of truth is what makes the wizard and the unattended file
provably equivalent: both go through :func:`validate` before anything is
written to disk.
"""

from __future__ import annotations

